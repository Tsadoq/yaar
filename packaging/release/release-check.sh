#!/bin/sh
# Shows what release.sh does against a bare repository made as the remote, with a stand-in gh that
# only records its arguments: nothing when releases are off or there is nothing to release, one
# push of the bump commit and the tag when there is, and a refusal when main moved or the tag exists.
# packaging/release/release-check.sh (needs git; reads nothing but the scripts of this folder)
set -eu

NAME=release-check.sh
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
fail() {
  echo "$NAME: $*" >&2
  exit 1
}
[ $# -eq 0 ] || { echo "usage: packaging/release/release-check.sh" >&2; exit 2; }
[ -x "$HERE/release.sh" ] || fail "$HERE/release.sh is not an executable file"
command -v git > /dev/null 2>&1 || fail "git is not installed"

TMP=$(mktemp -d "${TMPDIR:-/tmp}/release-check.XXXXXX") || fail "no scratch folder could be made"
trap 'rm -rf "$TMP"' EXIT
# No identity: release.sh must bring its own, and the commits of the setup name theirs with -c.
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
unset GIT_AUTHOR_NAME GIT_AUTHOR_EMAIL GIT_COMMITTER_NAME GIT_COMMITTER_EMAIL || true
g() { git -c user.name=setup -c user.email=setup@example.invalid "$@"; }

mkdir "$TMP/bin"
cat > "$TMP/bin/gh" << 'GH'
#!/bin/sh
printf '%s\n' "$*" >> "$GH_LOG"
[ -z "${GH_FAIL:-}" ] || exit 1
GH
chmod +x "$TMP/bin/gh"

CASES=0
# new_case <name> [tagged]: a remote, and a clone of it whose main holds the scaffold of a workspace at
# 0.1.0, tagged v0.1.0 when asked. Afterwards $REMOTE, $WORK, $GH_LOG and $HOOKS name what the case
# watches.
new_case() {
  CASES=$((CASES + 1))
  D=$TMP/$1
  REMOTE=$D/remote.git
  WORK=$D/work
  GH_LOG=$D/gh.log
  HOOKS=$D/hooks.log
  mkdir "$D"
  : > "$GH_LOG"
  : > "$HOOKS"
  git init -q --bare "$REMOTE"
  git -C "$REMOTE" symbolic-ref HEAD refs/heads/main
  mkdir -p "$WORK/packaging/release"
  cd "$WORK"
  git init -q .
  git symbolic-ref HEAD refs/heads/main
  cp "$ROOT/packaging/version.sh" packaging/version.sh
  for f in next-version.sh bump.sh release.sh commit-subject; do cp "$HERE/$f" "packaging/release/$f"; done
  printf '[workspace]\nmembers = ["a"]\n\n[workspace.package]\nversion = "0.1.0"\n' > Cargo.toml
  mkdir a
  printf '[package]\nname = "yaar-a"\nversion.workspace = true\n' > a/Cargo.toml
  cat > Cargo.lock << 'LOCK'
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "serde"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "yaar-a"
version = "0.1.0"
LOCK
  git add .
  g commit -q -m 'chore: start the scratch repository'
  git remote add origin "$REMOTE"
  git push -q origin main
  if [ "${2:-}" = tagged ]; then
    g tag -a v0.1.0 -m v0.1.0
    git push -q origin v0.1.0
  fi
  # One line for each push the remote takes, naming the refs it updates.
  cat > "$REMOTE/hooks/pre-receive" << HOOK
#!/bin/sh
{ printf 'push:'; while read -r old new ref; do printf ' %s' "\$ref"; done; echo; } >> "$HOOKS"
HOOK
  chmod +x "$REMOTE/hooks/pre-receive"
}
land() { # <subject>: a commit on main, pushed
  g commit -q --allow-empty -m "$1"
  git push -q origin main
}
ref_of() { git -C "$REMOTE" rev-parse --verify --quiet "$1" || echo "no $1"; }
remote_refs() { git -C "$REMOTE" for-each-ref; }
# release [VAR=value]...: runs release.sh in $WORK; leaves $STATUS and $SAID.
release() {
  : > "$GH_LOG"
  : > "$HOOKS"
  STATUS=0
  (cd "$WORK" && env PATH="$TMP/bin:$PATH" GH_LOG="$GH_LOG" "$@" sh packaging/release/release.sh) > "$TMP/out" 2> "$TMP/err" || STATUS=$?
  SAID=$(cat "$TMP/out" "$TMP/err")
}
nothing_pushed() { # <what it shows> <refs before>
  [ "$(remote_refs)" = "$2" ] || fail "$1: the remote changed: $(remote_refs | tr '\n' ' ')"
  [ ! -s "$HOOKS" ] || fail "$1: the remote took a push: $(cat "$HOOKS")"
  [ ! -s "$GH_LOG" ] || fail "$1: gh was called: $(cat "$GH_LOG")"
}
says() { # <what it shows> <words>
  case $SAID in
    *"$2"*) ;;
    *) fail "$1: the sentence does not say '$2': $SAID" ;;
  esac
}

# Releases are off: a variable that is not 'on', or none.
new_case off tagged
land 'fix: mend it'
BEFORE=$(remote_refs)
for setting in RELEASES= RELEASES=off RELEASES=ON RELEASES=1 RELEASES=true; do
  release "$setting"
  [ "$STATUS" -eq 0 ] || fail "off ($setting): release.sh exited $STATUS: $SAID"
  says "off ($setting)" "automatic releases are off"
  says "off ($setting)" "the next version would be 0.1.1"
  nothing_pushed "off ($setting)" "$BEFORE"
  [ -z "$(git -C "$WORK" status --porcelain)" ] || fail "off ($setting): it changed the tree"
done
: > "$GH_LOG"
: > "$HOOKS"
STATUS=0
(cd "$WORK" && env -u RELEASES PATH="$TMP/bin:$PATH" GH_LOG="$GH_LOG" sh packaging/release/release.sh) > "$TMP/out" 2> "$TMP/err" || STATUS=$?
SAID=$(cat "$TMP/out" "$TMP/err")
[ "$STATUS" -eq 0 ] || fail "off (no variable): release.sh exited $STATUS: $SAID"
says "off (no variable)" "automatic releases are off"
nothing_pushed "off (no variable)" "$BEFORE"

new_case off-and-nothing tagged
land 'docs: say it'
BEFORE=$(remote_refs)
release RELEASES=off
[ "$STATUS" -eq 0 ] || fail "off with nothing to release: release.sh exited $STATUS: $SAID"
says "off with nothing to release" "automatic releases are off"
says "off with nothing to release" "nothing to release"
nothing_pushed "off with nothing to release" "$BEFORE"

# Nothing to release.
new_case nothing tagged
land 'docs: say it'
land 'chore: tidy'
land 'ci: run it'
BEFORE=$(remote_refs)
release RELEASES=on
[ "$STATUS" -eq 0 ] || fail "nothing to release: release.sh exited $STATUS: $SAID"
says "nothing to release" "nothing to release"
nothing_pushed "nothing to release" "$BEFORE"

# A fix: the bump commit and the tag go out in one push, and the run starts.
new_case feat tagged
land 'fix: mend it'
land 'feat(link): add it'
land 'fix: mend it again'
WAS=$(git -C "$REMOTE" rev-parse main)
release RELEASES=on
[ "$STATUS" -eq 0 ] || fail "a feat: release.sh exited $STATUS: $SAID"
TIP=$(git -C "$REMOTE" rev-parse main)
[ "$TIP" != "$WAS" ] || fail "a feat: main of the remote did not move"
[ "$(git -C "$REMOTE" rev-parse "main^")" = "$WAS" ] || fail "a feat: main of the remote is not the old main and one commit"
[ "$(git -C "$REMOTE" log -1 --format=%s main)" = 'chore(release): v0.2.0' ] \
  || fail "a feat: the commit on main is '$(git -C "$REMOTE" log -1 --format=%s main)', not 'chore(release): v0.2.0'"
[ "$(git -C "$REMOTE" log -1 --format='%an <%ae>' main)" = 'github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>' ] \
  || fail "a feat: the author of the release commit is $(git -C "$REMOTE" log -1 --format='%an <%ae>' main)"
[ "$(git -C "$REMOTE" log -1 --format='%cn <%ce>' main)" = 'github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>' ] \
  || fail "a feat: the committer of the release commit is $(git -C "$REMOTE" log -1 --format='%cn <%ce>' main)"
[ "$(ref_of 'v0.2.0^{commit}')" = "$TIP" ] || fail "a feat: the tag v0.2.0 is not on the release commit"
[ "$(git -C "$REMOTE" tag -l | tr '\n' ' ')" = 'v0.1.0 v0.2.0 ' ] || fail "a feat: the tags of the remote are $(git -C "$REMOTE" tag -l | tr '\n' ' ')"
[ "$(cat "$HOOKS")" = 'push: refs/heads/main refs/tags/v0.2.0' ] || [ "$(cat "$HOOKS")" = 'push: refs/tags/v0.2.0 refs/heads/main' ] \
  || fail "a feat: the commit and the tag did not go in one push: $(cat "$HOOKS")"
[ "$(cat "$GH_LOG")" = 'workflow run ci.yml --ref v0.2.0 -f publish=true' ] || fail "a feat: gh was called with: $(cat "$GH_LOG")"
git -C "$REMOTE" show main:Cargo.toml | grep -q '^version = "0.2.0"$' || fail "a feat: Cargo.toml of the release commit does not hold 0.2.0"
[ "$(git -C "$REMOTE" show main:Cargo.lock | grep -c '^version = "0.2.0"$')" -eq 1 ] || fail "a feat: Cargo.lock of the release commit does not hold 0.2.0 for the member alone"
git -C "$REMOTE" show main:Cargo.lock | grep -q '^version = "0.1.0"$' || fail "a feat: the crate of a registry lost its version in Cargo.lock"
[ "$(git -C "$REMOTE" diff --name-only "$WAS" main | tr '\n' ' ')" = 'Cargo.lock Cargo.toml ' ] || fail "a feat: the release commit changes more than Cargo.toml and Cargo.lock"
(cd "$WORK" && "$ROOT/.github/scripts/commit-lint.sh" "$WAS" HEAD > /dev/null 2> "$TMP/err") \
  || fail "a feat: the release commit does not hold the form commit-lint.sh asks: $(cat "$TMP/err")"
says "a feat" "v0.2.0"

# A second run on the release commit has nothing to release.
BEFORE=$(remote_refs)
release RELEASES=on
[ "$STATUS" -eq 0 ] || fail "a second run: release.sh exited $STATUS: $SAID"
says "a second run" "nothing to release"
nothing_pushed "a second run" "$BEFORE"

new_case fix-only tagged
land 'fix: mend it'
release RELEASES=on
[ "$STATUS" -eq 0 ] || fail "a fix: release.sh exited $STATUS: $SAID"
[ "$(git -C "$REMOTE" log -1 --format=%s main)" = 'chore(release): v0.1.1' ] || fail "a fix: the commit on main is '$(git -C "$REMOTE" log -1 --format=%s main)'"
[ "$(ref_of 'v0.1.1^{commit}')" = "$(git -C "$REMOTE" rev-parse main)" ] || fail "a fix: the tag v0.1.1 is not on main"
[ "$(cat "$GH_LOG")" = 'workflow run ci.yml --ref v0.1.1 -f publish=true' ] || fail "a fix: gh was called with: $(cat "$GH_LOG")"

# The first release: the tag stands on the present commit, and no commit is made.
new_case first
land 'feat: add it'
WAS=$(git -C "$REMOTE" rev-parse main)
release RELEASES=on
[ "$STATUS" -eq 0 ] || fail "the first release: release.sh exited $STATUS: $SAID"
[ "$(git -C "$REMOTE" rev-parse main)" = "$WAS" ] || fail "the first release: main of the remote moved: a commit was made"
[ "$(ref_of 'v0.1.0^{commit}')" = "$WAS" ] || fail "the first release: the tag v0.1.0 is not on the present commit"
[ "$(git -C "$REMOTE" tag -l | tr '\n' ' ')" = 'v0.1.0 ' ] || fail "the first release: the tags of the remote are $(git -C "$REMOTE" tag -l | tr '\n' ' ')"
[ "$(cat "$HOOKS")" = 'push: refs/tags/v0.1.0' ] || fail "the first release: the push updated $(cat "$HOOKS")"
[ "$(cat "$GH_LOG")" = 'workflow run ci.yml --ref v0.1.0 -f publish=true' ] || fail "the first release: gh was called with: $(cat "$GH_LOG")"
git -C "$REMOTE" show main:Cargo.toml | grep -q '^version = "0.1.0"$' || fail "the first release: Cargo.toml no longer holds 0.1.0"

# main moved while the run went: the push is refused as a whole.
new_case moved tagged
land 'fix: mend it'
git clone -q "$REMOTE" "$TMP/moved/other"
(cd "$TMP/moved/other" && g commit -q --allow-empty -m 'docs: a commit that landed meanwhile' && git push -q origin main)
BEFORE=$(remote_refs)
release RELEASES=on
[ "$STATUS" -eq 1 ] || fail "main moved: release.sh exited $STATUS and not 1: $SAID"
says "main moved" "main moved"
says "main moved" "the next run on main releases"
[ "$(remote_refs)" = "$BEFORE" ] || fail "main moved: the remote changed: $(remote_refs | tr '\n' ' ')"
[ "$(git -C "$REMOTE" tag -l | tr '\n' ' ')" = 'v0.1.0 ' ] || fail "main moved: a tag went to the remote: $(git -C "$REMOTE" tag -l | tr '\n' ' ')"
[ ! -s "$GH_LOG" ] || fail "main moved: gh was called: $(cat "$GH_LOG")"

# The tag exists already, on the remote only, or here on a commit that HEAD does not reach.
new_case tag-on-remote tagged
land 'fix: mend it'
git clone -q "$REMOTE" "$TMP/tag-on-remote/other"
(cd "$TMP/tag-on-remote/other" && g tag v0.1.1 HEAD~1 && git push -q origin v0.1.1)
BEFORE=$(remote_refs)
release RELEASES=on
[ "$STATUS" -eq 1 ] || fail "a tag on the remote: release.sh exited $STATUS and not 1: $SAID"
says "a tag on the remote" "the tag v0.1.1 exists already"
[ "$(remote_refs)" = "$BEFORE" ] || fail "a tag on the remote: the remote changed"
[ ! -s "$GH_LOG" ] || fail "a tag on the remote: gh was called: $(cat "$GH_LOG")"

new_case tag-here tagged
git checkout -q -b side
g commit -q --allow-empty -m 'chore: a commit that main does not reach'
g tag v0.1.1
git checkout -q main
land 'fix: mend it'
BEFORE=$(remote_refs)
release RELEASES=on
[ "$STATUS" -eq 1 ] || fail "a tag here: release.sh exited $STATUS and not 1: $SAID"
says "a tag here" "the tag v0.1.1 exists already"
[ "$(remote_refs)" = "$BEFORE" ] || fail "a tag here: the remote changed"
[ ! -s "$GH_LOG" ] || fail "a tag here: gh was called: $(cat "$GH_LOG")"

# gh fails after the push: the sentence says how to start the run.
new_case gh-fails tagged
land 'fix: mend it'
release RELEASES=on GH_FAIL=1
[ "$STATUS" -eq 1 ] || fail "gh fails: release.sh exited $STATUS and not 1: $SAID"
says "gh fails" "gh workflow run ci.yml --ref v0.1.1 -f publish=true"
[ "$(git -C "$REMOTE" tag -l | tr '\n' ' ')" = 'v0.1.0 v0.1.1 ' ] || fail "gh fails: the tag is not on the remote"

# A bump that bump.sh refuses: Cargo.toml was raised by hand above the version to release.
new_case ahead tagged
sed 's/^version = "0.1.0"/version = "0.5.0"/' Cargo.toml > Cargo.toml.new
mv Cargo.toml.new Cargo.toml
g commit -q -a -m 'chore: raise the version by hand'
land 'fix: mend it'
BEFORE=$(remote_refs)
release RELEASES=on
[ "$STATUS" -eq 1 ] || fail "a version by hand above the next: release.sh exited $STATUS and not 1: $SAID"
says "a version by hand above the next" "not greater than the present version 0.5.0"
nothing_pushed "a version by hand above the next" "$BEFORE"

echo "$NAME: the $CASES scratch remotes show it: off and nothing to release push nothing, a release is one push and one run, and a moved main or a tag that exists is refused"
